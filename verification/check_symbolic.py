#!/usr/bin/env python3
"""Bounded integer SMT obligations for reserve math, not Rust symbolic execution."""
import argparse
import hashlib
import json
from pathlib import Path

import z3

ROOT = Path(__file__).resolve().parents[1]
Q = 10**24
MAX = 100 * Q  # clearinghouse MAX_SUPPLY, native atomic units
BASE_COEFFICIENTS = (0, 1, Q // 3, 2 * Q // 3, Q - 1, Q)
COEFFICIENTS = tuple(sorted(set(BASE_COEFFICIENTS) | {Q - c for c in BASE_COEFFICIENTS}))


def run(check):
    if z3.get_version_string() != "4.15.4":
        raise RuntimeError("use pinned z3-solver==4.15.4.0")
    report = {"solver": z3.get_version_string(), "scale": str(Q), "max_supply": str(MAX),
              "coefficients": [str(c) for c in COEFFICIENTS], "obligations": [],
              "scope": "Bounded integer abstraction at eight complement-closed coefficients; not symbolic execution or refinement of Rust/Wasm"}
    directory = ROOT / "verification/smt"
    if not check:
        directory.mkdir(exist_ok=True)

    def query(name, assumptions, violation, variables, expect="unsat"):
        solver = z3.Solver()
        solver.set(timeout=10000, random_seed=0)
        solver.add(*assumptions)
        if solver.check() != z3.sat:
            raise RuntimeError(f"{name}: assumptions must be satisfiable")
        solver.add(violation)
        smt = "; SEC-01 bounded integer abstraction; generated by check_symbolic.py\n" + solver.sexpr() + "\n(check-sat)\n"
        destination = directory / (name + ".smt2")
        if check:
            if destination.read_text() != smt:
                raise RuntimeError(f"stale SMT obligation: {name}")
        else:
            destination.write_text(smt)
        result = str(solver.check())
        if result != expect:
            raise RuntimeError(f"{name}: expected {expect}, got {result}; {solver.reason_unknown()}")
        record = {"name": name, "assumptions": "sat", "result": result, "smt_sha256": hashlib.sha256(smt.encode()).hexdigest()}
        if result == "sat":
            model = solver.model()
            record["counterexample"] = {str(v): str(model.eval(v, model_completion=True)) for v in variables}
        report["obligations"].append(record)
        print(f"PASS {name}: {result}")
        return record

    x, y, amount, other, reserve, paid, backing = z3.Ints("x y amount other reserve paid backing")
    bounded = lambda v: z3.And(v >= 0, v <= MAX)
    for index, coefficient in enumerate(COEFFICIENTS):
        # Z3 Int division is floor for the nonnegative operands constrained here.
        payout = lambda a: a * coefficient / Q
        complement = lambda a: a * (Q - coefficient) / Q
        query(f"initial-backing-{index}", [bounded(x)],
              payout(x) + complement(x) > x, [x])
        query(f"fragmentation-{index}", [bounded(x), bounded(y), x + y <= MAX],
              payout(x) + payout(y) > payout(x + y), [x, y])
        old_obligation = payout(x) + complement(other)
        after = reserve - payout(amount)
        query(f"redemption-{index}",
              [bounded(x), bounded(other), bounded(amount), amount > 0, amount <= x,
               bounded(reserve), bounded(paid), bounded(backing), reserve + paid == backing,
               reserve >= old_obligation],
              z3.Or(after < payout(x - amount) + complement(other),
                    paid + payout(amount) > backing, after + paid + payout(amount) != backing),
              [x, other, amount, reserve, paid, backing])
        query(f"wide-product-{index}", [bounded(amount)],
              z3.Or(amount * coefficient >= 2**256, payout(amount) >= 2**128, payout(amount) > amount), [amount])

    # Mutation controls must exhibit concrete violations; validate witnesses using
    # ordinary Python integers too, independently of Z3 expression construction.
    c = Q // 3
    rounded_up = (amount * c + Q - 1) / Q
    mutation = query("mutation-round-up", [bounded(x), x > 0, bounded(amount), amount > 0, amount <= x],
                     rounded_up + ((x - amount) * c / Q) > x * c / Q, [x, amount], "sat")
    witness = mutation["counterexample"]
    a, b = int(witness["amount"]), int(witness["x"])
    if (a * c + Q - 1) // Q + (b - a) * c // Q <= b * c // Q:
        raise RuntimeError("invalid rounding counterexample")
    files = ["verification/check_symbolic.py", "verification/requirements.txt", "crates/payoff-math/src/lib.rs",
             "contracts/clearinghouse/src/claims.rs", "contracts/clearinghouse/src/types.rs"]
    report["sources"] = {f: hashlib.sha256((ROOT / f).read_bytes()).hexdigest() for f in files}
    report["passed"] = True
    destination = ROOT / "research/reports/g8-symbolic.json"
    encoded = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if check:
        if destination.read_text() != encoded:
            raise RuntimeError("symbolic evidence differs; regenerate and review")
    else:
        destination.write_text(encoded)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    run(parser.parse_args().check)
